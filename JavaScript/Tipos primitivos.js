// Tipos primitivos em JavaScript

let nome = "Samuel";                         // string
let idade = 18;                              // number
let altura = 1.85;                           // number
let estudante = true;                        // boolean
let numeroGigante = 9007199254740993n;       // bigint
let identificador = Symbol("id");            // symbol
let resultado = null;                        // null

console.log("Nome:", nome, "| Tipo:", typeof nome);
console.log("Idade:", idade, "| Tipo:", typeof idade);
console.log("Altura:", altura, "| Tipo:", typeof altura);
console.log("Estudante:", estudante, "| Tipo:", typeof estudante);
console.log("Número gigante:", numeroGigante, "| Tipo:", typeof numeroGigante);
console.log("Identificador:", identificador, "| Tipo:", typeof identificador);
console.log("Resultado:", resultado, "| Tipo:", typeof resultado);
